//! Derives the migration tail both lineages append after the frozen cutover.
//!
//! See `src/storage/migration_files.rs` for the grammar, which this script
//! compiles in by path so the build and the tests read the directory one way.

#[path = "src/storage/migration_files.rs"]
#[allow(dead_code)]
mod migration_files;

use std::fmt::Write as _;
use std::path::Path;

use migration_files::{derive_tail, RebuildSpec, TailMigration};

const DIRECTORY: &str = "../../turso_migrations";

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/storage/migration_files.rs");
    println!("cargo:rerun-if-changed={DIRECTORY}");

    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR");
    let directory = Path::new(&manifest).join(DIRECTORY);
    let mut files: Vec<(String, String)> = Vec::new();
    let entries = std::fs::read_dir(&directory)
        .unwrap_or_else(|error| panic!("read {}: {error}", directory.display()));
    for entry in entries {
        let entry = entry.unwrap_or_else(|error| panic!("list {}: {error}", directory.display()));
        let name = entry.file_name().to_string_lossy().into_owned();
        if !name.ends_with(".sql") {
            continue;
        }
        let content = std::fs::read_to_string(entry.path())
            .unwrap_or_else(|error| panic!("read {}: {error}", entry.path().display()));
        files.push((name, content));
    }
    files.sort();

    let tail = match derive_tail(&files) {
        Ok(tail) => tail,
        Err(error) => panic!("migration tail in src-tauri/turso_migrations: {error}"),
    };
    let private: Vec<&TailMigration> = tail
        .iter()
        .filter(|migration| migration.headers.lineage.reaches_private())
        .collect();
    let team: Vec<&TailMigration> = tail
        .iter()
        .filter(|migration| migration.headers.lineage.reaches_team())
        .collect();

    let mut out = String::from(
        "// @generated by cairn-db's build.rs from src-tauri/turso_migrations; do not edit.\n\n",
    );
    write_composer(&mut out, "with_private_tail", &private);
    write_composer(&mut out, "with_team_tail", &team);
    write_stems(&mut out, "DERIVED_PRIVATE_TAIL", &private);
    write_stems(&mut out, "DERIVED_TEAM_TAIL", &team);

    let generated =
        Path::new(&std::env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("migration_tail.rs");
    std::fs::write(&generated, out)
        .unwrap_or_else(|error| panic!("write {}: {error}", generated.display()));
}

/// A composer that closes a lineage's array: the hand-composed items, then the
/// derived tail. A `macro_rules!` invocation in array-element position expands
/// to exactly one expression, so the tail cannot be spliced in as a list; the
/// lineage composers hand their items to this macro instead.
fn write_composer(out: &mut String, name: &str, tail: &[&TailMigration]) {
    let _ = writeln!(out, "macro_rules! {name} {{");
    let _ = writeln!(out, "    ($($item:expr),* $(,)?) => {{");
    let _ = writeln!(out, "        &[");
    let _ = writeln!(out, "            $($item,)*");
    for migration in tail {
        let stem = &migration.stem;
        let sql = format!(
            "include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/{DIRECTORY}/{stem}.sql\"))"
        );
        match &migration.headers.rebuild_fk_off {
            None => {
                let _ = writeln!(
                    out,
                    "            Migration::new(version_from_stem(\"{stem}\"), name_from_stem(\"{stem}\"), {sql}),"
                );
            }
            Some(checks) => {
                let checks = checks
                    .iter()
                    .map(|check| match check {
                        RebuildSpec::Conserved(table) => {
                            format!("RebuildCheck::Conserved(\"{table}\")")
                        }
                        RebuildSpec::Reshaped(table) => {
                            format!("RebuildCheck::Reshaped(\"{table}\")")
                        }
                    })
                    .collect::<Vec<_>>()
                    .join(", ");
                let _ = writeln!(
                    out,
                    "            Migration::rebuild_fk_off(version_from_stem(\"{stem}\"), name_from_stem(\"{stem}\"), {sql}, &[{checks}]),"
                );
            }
        }
    }
    let _ = writeln!(out, "        ]");
    let _ = writeln!(out, "    }};");
    let _ = writeln!(out, "}}\n");
}

fn write_stems(out: &mut String, name: &str, tail: &[&TailMigration]) {
    let stems = tail
        .iter()
        .map(|migration| format!("\"{}\"", migration.stem))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(
        out,
        "/// The stems this lineage's derived tail applies, in order.\n#[allow(dead_code)]\npub(crate) const {name}: &[&str] = &[{stems}];\n"
    );
}
