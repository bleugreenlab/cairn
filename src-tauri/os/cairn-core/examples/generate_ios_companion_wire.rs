const PROTOCOL_SOURCE: &str = include_str!("../../cairn-common/src/companion_protocol.rs");
const PROJECTION_SOURCE: &str = include_str!("../src/companion_projection.rs");

fn description(source: &str) -> &str {
    source
        .split("// IOS_WIRE_DESCRIPTION_BEGIN")
        .nth(1)
        .unwrap()
        .split("// IOS_WIRE_DESCRIPTION_END")
        .next()
        .unwrap()
        .trim()
}
fn version(name: &str) -> &str {
    PROTOCOL_SOURCE
        .split(&format!("pub const {name}: u32 = "))
        .nth(1)
        .unwrap()
        .split(';')
        .next()
        .unwrap()
}
fn main() {
    println!(
        "// Canonical protocol v{}, framing v{}",
        version("COMPANION_PROTOCOL_VERSION"),
        version("COMPANION_FRAMING_VERSION")
    );
    for line in description(PROTOCOL_SOURCE)
        .lines()
        .chain(description(PROJECTION_SOURCE).lines())
    {
        println!("// {}", line.trim());
    }
    print!(
        "{}",
        SWIFT
            .replace(
                "let companionProtocolVersion: UInt32 = 1",
                &format!(
                    "let companionProtocolVersion: UInt32 = {}",
                    version("COMPANION_PROTOCOL_VERSION")
                )
            )
            .replace(
                "let companionFramingVersion: UInt32 = 1",
                &format!(
                    "let companionFramingVersion: UInt32 = {}",
                    version("COMPANION_FRAMING_VERSION")
                )
            )
    );
}

