//! Derives `EXECUTOR_PROTOCOL_VERSION` from the paragraphs that describe it.
//!
//! See `src/executor_protocol_ledger.rs` for the grammar, which this script
//! compiles in by path so the build and the landing binder read the ledger one
//! way.

#[path = "src/executor_protocol_ledger.rs"]
#[allow(dead_code)]
mod executor_protocol_ledger;

use std::path::Path;

const SOURCE: &str = "src/executor_protocol.rs";

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/executor_protocol_ledger.rs");
    println!("cargo:rerun-if-changed={SOURCE}");

    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR");
    let source = Path::new(&manifest).join(SOURCE);
    let text = std::fs::read_to_string(&source)
        .unwrap_or_else(|error| panic!("read {}: {error}", source.display()));
    let version = executor_protocol_ledger::derive_version(&text, executor_protocol_ledger::ANCHOR)
        .unwrap_or_else(|error| panic!("{SOURCE}: {error}"));
    let version = u32::try_from(version)
        .unwrap_or_else(|_| panic!("{SOURCE}: protocol version {version} does not fit a u32"));

    let generated = Path::new(&std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"))
        .join("executor_protocol_version.rs");
    std::fs::write(
        &generated,
        format!(
            "// @generated by cairn-common's build.rs from {SOURCE}; do not edit.\n\
             pub const EXECUTOR_PROTOCOL_VERSION: u32 = {version};\n"
        ),
    )
    .unwrap_or_else(|error| panic!("write {}: {error}", generated.display()));
}
